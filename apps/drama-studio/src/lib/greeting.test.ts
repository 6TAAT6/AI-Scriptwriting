import { describe, expect, test } from 'vitest'
import { welcomeGreeting } from './greeting'

describe('首页问候语', () => {
  test.each([
    [0, '晚上好，开始创作吧！'],
    [4, '晚上好，开始创作吧！'],
    [5, '早上好，开始创作吧！'],
    [8, '早上好，开始创作吧！'],
    [9, '上午好，开始创作吧！'],
    [11, '上午好，开始创作吧！'],
    [12, '中午好，开始创作吧！'],
    [13, '中午好，开始创作吧！'],
    [14, '下午好，开始创作吧！'],
    [17, '下午好，开始创作吧！'],
    [18, '晚上好，开始创作吧！'],
    [21, '晚上好，开始创作吧！'],
    [22, '晚上好，开始创作吧！'],
    [23, '晚上好，开始创作吧！'],
  ])('按本地小时 %i 返回对应的主标题', (hour, expected) => {
    expect(welcomeGreeting(hour)).toBe(expected)
  })
})
