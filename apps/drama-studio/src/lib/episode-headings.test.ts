import { expect, test } from 'vitest'
import { emphasizeEpisodeHeadings } from './episode-headings'

test('集标题行显示为小标题，统计说明与正文不变', () => {
  const text = ['第05集 去不了的车站', '', '△莉莉抱着空煤桶。', '', '第06集 她替谁签字', '**第7集《不是买来的》**', '第1集：893字（落在区间内）',
    '第2集正文实际1774个非空白字符。', '> 第3集', '```', '第4集', '```'].join('\n')
  expect(emphasizeEpisodeHeadings(text).split('\n')).toEqual(['### 第05集 去不了的车站', '', '△莉莉抱着空煤桶。', '', '### 第06集 她替谁签字',
    '### 第7集《不是买来的》', '第1集：893字（落在区间内）', '第2集正文实际1774个非空白字符。', '> 第3集', '```', '第4集', '```'])
})

test('场次标题显示为四级小标题，动作与台词不变', () => {
  const text = ['9-1场  冰峰堡垒中央祭典广场  夜  外', '', '人物：艾拉、卢卡斯', '', '△寒风裹挟蓝焰剧烈晃动。', '', '卢卡斯：各位长老，真正出卖防御图腾的人，正是她！', '1-2 书房 日 内', '第1集第2场写得很好。']
  expect(emphasizeEpisodeHeadings(text.join('\n'), true).split('\n')).toEqual(['#### 9-1场  冰峰堡垒中央祭典广场  夜  外', '', '人物：艾拉、卢卡斯', '', '△寒风裹挟蓝焰剧烈晃动。', '',
    '卢卡斯：各位长老，真正出卖防御图腾的人，正是她！', '', '#### 1-2 书房 日 内', '第1集第2场写得很好。'])
})

test('只用单个换行分隔的剧本行在显示时分成独立段落', () => {
  const text = '人物：艾拉、莫拉\n△寒风卷起冰屑。\n莫拉：（低声）小姐。\n艾拉：走。\n- 列表项\n- 列表项'
  expect(emphasizeEpisodeHeadings(text, true).split('\n')).toEqual(['人物：艾拉、莫拉', '', '△寒风卷起冰屑。', '', '莫拉：（低声）小姐。', '', '艾拉：走。', '- 列表项', '- 列表项'])
})
